#!/usr/bin/env python3
"""Rebuild LaTeX tables and provenance from the versioned integration run.

Requires only the Python standard library. ``--check`` verifies every generated
artifact without creating directories or changing files. No raw observations,
model weights, or local run outputs are read or copied.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


REPORT_DIR = Path(__file__).resolve().parent
SOURCE_RELATIVE_PATH = "../../evidence/run-summary.json"
IMPLEMENTATION_COMMIT = "693bcc4331a2df80402496492ccfa1a237f90c7a"
GENERATED_NOTICE = "% Generated by generate_tables.py from evidence/run-summary.json.\n"


def number(value: float, places: int = 2) -> str:
    return f"{value:.{places}f}"


def percent(value: float, places: int = 3) -> str:
    return number(100 * value, places) + r"\%"


def tabular(columns: str, headings: list[str], rows: list[list[str]]) -> bytes:
    lines = [
        GENERATED_NOTICE.rstrip(),
        r"\begin{tabular}{" + columns + "}",
        r"\toprule",
        " & ".join(headings) + r" \\",
        r"\midrule",
    ]
    lines.extend(" & ".join(row) + r" \\" for row in rows)
    lines.extend([r"\bottomrule", r"\end{tabular}", ""])
    return "\n".join(lines).encode("utf-8")


def utc_label(value: str) -> str:
    instant = datetime.fromisoformat(value)
    if instant.tzinfo is None:
        raise ValueError("Label timestamps must specify a UTC offset")
    return instant.astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M")


def build_artifacts(source_bytes: bytes) -> dict[str, bytes]:
    source: dict[str, Any] = json.loads(source_bytes)
    walk_forward = source["walk_forward"]
    metrics = walk_forward["metrics"]
    baseline = metrics["baseline"]
    raw = metrics["model_raw"]
    calibrated = metrics["model_calibrated"]
    artifacts: dict[str, bytes] = {}

    point_rows = []
    for label, metric in [("Persistence", baseline), ("Kronos-base", raw)]:
        point_rows.append([
            label,
            number(metric["close_mae"]),
            number(metric["close_rmse"]),
            number(metric["return_mae_pct"]),
            percent(metric["directional_accuracy"], 2),
            "--" if metric["brier_score"] is None else number(metric["brier_score"], 5),
        ])
    artifacts["tables/base-point.tex"] = tabular(
        "lrrrrr",
        ["Method", "MAE", "RMSE", "Return MAE", "Direction acc.", "Brier"],
        point_rows,
    )

    interval_rows = []
    for label, metric in [("Raw", raw), ("Calibrated", calibrated)]:
        interval_rows.append([
            label,
            percent(metric["coverage80"]),
            number(metric["mean_interval_width"]),
            number(metric["mean_pinball_loss"]),
        ])
    artifacts["tables/base-interval.tex"] = tabular(
        "lrrr", ["Method", "Coverage", "Width", "Pinball"], interval_rows,
    )

    ablation_rows = []
    for name in ("zero-shot", "predictor-only", "two-stage"):
        variant = source["ablation"]["variants"][name]
        steps = variant["training_steps"]
        stage_steps = []
        if "tokenizer" in steps:
            stage_steps.append(f"{steps['tokenizer']} T")
        if "predictor" in steps:
            stage_steps.append(f"{steps['predictor']} P")
        test_metrics = variant["test_metrics"]
        ablation_raw = test_metrics["model_raw"]
        ablation_cal = test_metrics["model_calibrated"]
        ablation_rows.append([
            name,
            " + ".join(stage_steps) if stage_steps else "0",
            number(ablation_raw["close_mae"]),
            number(ablation_raw["close_rmse"]),
            percent(ablation_raw["coverage80"]),
            percent(ablation_cal["coverage80"]),
        ])
    artifacts["tables/ablation.tex"] = tabular(
        "llrrrr", ["Variant", "Steps", "MAE", "RMSE", "Raw cov.", "Cal. cov."],
        ablation_rows,
    )

    split_rows = []
    for key, label in [("calibration", "Calibration"), ("test", "Test")]:
        split = walk_forward["split"][key]
        split_rows.append([
            label,
            str(split["first_origin_index"]),
            str(split["last_origin_index"]),
            utc_label(split["first_label_timestamp"]),
            utc_label(split["last_label_timestamp"]),
        ])
    artifacts["tables/splits.tex"] = tabular(
        "lrrll", ["Split", "First origin", "Last origin", "Label start", "Label end"],
        split_rows,
    )

    expansions = walk_forward["calibration"]["expansion_by_horizon"]
    if len(expansions) != 8:
        raise ValueError("The recorded report configuration requires eight forecast horizons")
    artifacts["tables/calibration.tex"] = tabular(
        "rr", ["Horizon", "Expansion"],
        [[str(horizon), number(expansion)] for horizon, expansion in enumerate(expansions, 1)],
    )

    macros = {
        "BaseMAE": number(raw["close_mae"]),
        "BaselineMAE": number(baseline["close_mae"]),
        "MAEReductionPercent": percent(1 - raw["close_mae"] / baseline["close_mae"], 2),
        "RawCoverage": percent(raw["coverage80"]),
        "CalCoverage": percent(calibrated["coverage80"]),
        "RawWidth": number(raw["mean_interval_width"]),
        "CalWidth": number(calibrated["mean_interval_width"]),
        "WidthRatio": number(calibrated["mean_interval_width"] / raw["mean_interval_width"]),
        "RawPinball": number(raw["mean_pinball_loss"]),
        "CalPinball": number(calibrated["mean_pinball_loss"]),
    }
    artifacts["tables/metrics.tex"] = (
        GENERATED_NOTICE
        + "".join("\\newcommand{\\" + name + "}{" + value + "}\n" for name, value in macros.items())
    ).encode("utf-8")

    manifest = {
        "source": SOURCE_RELATIVE_PATH,
        "sha256": hashlib.sha256(source_bytes).hexdigest(),
        "recorded_at_utc": source["recorded_at_utc"],
        "implementation_commit": IMPLEMENTATION_COMMIT,
        "upstream_revision": source["upstream_revision"],
        "model_revisions": {
            "forecast_model": source["real_forecast"]["model"],
            "forecast_tokenizer": source["real_forecast"]["tokenizer"],
            "ablation_initial_checkpoints": source["ablation"]["initial_checkpoints"],
            "ablation_trained_checkpoint_hashes": {
                name: variant["checkpoint_hashes"]
                for name, variant in source["ablation"]["variants"].items()
                if "checkpoint_hashes" in variant
            },
            "chronos2": {
                "id": source["chronos2"]["metadata"]["model"],
                "revision": source["chronos2"]["metadata"]["revision"],
            },
        },
        "data": source["data"],
        "forecast_input_sha256": source["real_forecast"]["input_sha256"],
    }
    artifacts["evidence-manifest.json"] = (
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"
    ).encode("utf-8")
    return artifacts


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify generated files without writing")
    args = parser.parse_args()
    try:
        artifacts = build_artifacts((REPORT_DIR / SOURCE_RELATIVE_PATH).read_bytes())
        mismatches = []
        for relative_path, expected in artifacts.items():
            destination = REPORT_DIR / relative_path
            if args.check:
                if not destination.is_file():
                    mismatches.append(f"Missing: {relative_path}")
                elif destination.read_bytes() != expected:
                    mismatches.append(f"Out of date: {relative_path}")
            else:
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_bytes(expected)
        if mismatches:
            print("\n".join(mismatches), file=sys.stderr)
            print("Run python3 generate_tables.py to rebuild report artifacts.", file=sys.stderr)
            return 1
    except (OSError, ValueError, KeyError, TypeError, ZeroDivisionError) as error:
        print(f"Cannot generate report artifacts: {error}", file=sys.stderr)
        return 1
    action = "Verified" if args.check else "Generated"
    print(f"{action} {len(artifacts)} report artifacts from evidence/run-summary.json.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
